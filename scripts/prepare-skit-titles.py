#!/usr/bin/env python3
"""Build the bundled PC skit title and test-map ID catalog from the research export.

Usage (from skit-editor):
  python3 scripts/prepare-skit-titles.py ../tos-60-experiments/skit-id/skit-names-and-ids.json

The input is generated by tos-60-experiments/skit-id/export_skit_names.py from
the executable's filename/title tables and the English APPKEEP/TOS_TEXT.TXB.
Only canonical filenames, selector IDs and exact source titles enter the catalog.
Blank titles remain blank; noncanonical selector aliases are excluded.
"""

import argparse
import json
import pathlib
import re


def catalog_from_export(source):
    if not isinstance(source, dict) or not isinstance(source.get("rows"), list):
        raise ValueError("Expected a research export object containing a rows array")
    catalog = {}
    ids = set()
    for index, row in enumerate(source["rows"]):
        if not isinstance(row, dict) or not isinstance(row.get("canonical"), bool):
            raise ValueError(f"Row {index} needs a boolean canonical flag")
        if not row["canonical"]:
            continue
        filename, title, ident = row.get("filename"), row.get("title"), row.get("id")
        if not isinstance(filename, str) or not re.fullmatch(r"FC_[CBMUW][0-9]{3}\.SKP", filename.upper()):
            raise ValueError(f"Row {index} has an invalid canonical skit filename")
        if not isinstance(title, str) or any(ord(character) < 32 for character in title):
            raise ValueError(f"Row {index} needs a title string without control characters")
        if type(ident) is not int or ident <= 0:
            raise ValueError(f"Row {index} needs a positive integer skit ID")
        key = filename.upper()
        if key in catalog:
            raise ValueError(f"Duplicate canonical filename: {key}")
        if ident in ids:
            raise ValueError(f"Duplicate canonical skit ID: {ident}")
        ids.add(ident)
        catalog[key] = {"id": ident, "title": title}
    if not catalog:
        raise ValueError("The research export contains no canonical skit filenames")
    return dict(sorted(catalog.items()))


def main():
    project = pathlib.Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=pathlib.Path)
    parser.add_argument("--output", type=pathlib.Path, default=project / "src/skit-titles.json")
    args = parser.parse_args()
    try:
        catalog = catalog_from_export(json.loads(args.source.read_text(encoding="utf-8")))
    except (OSError, ValueError) as error:
        parser.error(str(error))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    named = sum(bool(slot["title"]) for slot in catalog.values())
    print(f"Prepared {len(catalog)} skit slots with IDs ({named} English titles) in {args.output}")


if __name__ == "__main__":
    main()
